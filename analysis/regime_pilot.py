#!/usr/bin/env python3
"""Damage-regime pilot (before Chunk 6): the same kind of deliberate reroute at
100 Mbit/s (results/dataset/regime-<date>, damage_design.py --grid) against
the Chunk 5 trials at 10 Mbit/s with the same source -> destination pair and
the same number of elephants on the destination. Labels and checks are
analysis/damage_dataset.py's (design mode). Deficit = no-move minus move;
shown in Mbit/s over the window and as a share of the link rate.

  .venv/bin/python analysis/regime_pilot.py --pilot results/dataset/regime-<date> \\
      --mbps 100 --chunk5 results/dataset/dataset-<date>/dataset/dataset.csv
writes <pilot>/regime_pilot.md and <pilot>/regime_pilot.csv.
"""

import argparse
import os
import sys

import numpy as np
import pandas as pd

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)
from analysis.damage_dataset import build_design  # noqa: E402
from analysis.gate import mean_ci  # noqa: E402

TERMS = [("moved_deficit_W2", 2), ("dest_total_deficit_W2", 2), ("dest_total_deficit_W10", 10)]


def mbps(df, col, w):
    return pd.to_numeric(df[col], errors="coerce") * 8 / w / 1e6


def cell(x, link):
    m, h = mean_ci(x)
    if np.isnan(m):
        return "n/a"
    s = "%.3f" % m if np.isnan(h) else "%.3f ± %.3f" % (m, h)
    return "%s (%.2f %%)" % (s, 100 * m / link)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--pilot", required=True)
    ap.add_argument("--mbps", type=float, default=100.0)
    ap.add_argument("--chunk5", required=True, help="Chunk 5 dataset.csv (10 Mbit/s)")
    a = ap.parse_args()
    hi = build_design(a.pilot)
    hi["rate"] = a.mbps
    lo = pd.read_csv(a.chunk5)
    lo = lo[(lo.source == "design") & (lo.replay_ok == 1)].copy()
    lo["rate"] = 10.0
    pairs = sorted(set(zip(hi.from_spine, hi.to_spine, hi.n_q_design)))
    rows, L = [], ["# Damage-regime pilot: %g Mbit/s vs 10 Mbit/s" % a.mbps, "",
                   "Generated by `analysis/regime_pilot.py`. Deficit = no-move minus move, "
                   "Mbit/s over the window, mean ± 95 %% CI over trials, and in brackets the share "
                   "of the link rate. %s trials at %g Mbit/s: %d with a label (%d excluded). The 10 "
                   "Mbit/s columns are the Chunk 5 trials with the same pair and destination load "
                   "(other factors differ)." % (os.path.basename(os.path.abspath(a.pilot)), a.mbps,
                                                int(hi.replay_ok.sum()),
                                                int((hi.replay_ok != 1).sum())), ""]
    head = ["pair", "elephants on q", "rate"] + [t for t, _ in TERMS] + \
        ["reordering seen W2 (move arm)", "retransmissions W2, move / no-move"]
    L += ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for p, q, nq in pairs:
        for name, d, link in (("%g" % a.mbps, hi, a.mbps), ("10", lo, 10.0)):
            g = d[(d.from_spine == p) & (d.to_spine == q) & (d.n_q_design == nq) & (d.replay_ok == 1)]
            r = dict(pair="s%d>s%d" % (p, q), n_q=nq, mbps=name, n=len(g))
            cells = []
            for t, w in TERMS:
                x = mbps(g, t, w)
                r[t + "_mbps"], r[t + "_ci"] = mean_ci(x)
                cells.append(cell(x, link))
            reo = "%d / %d, mean %.1f" % (int((g.ss_reord_seen_W2_T > 0).sum()), len(g),
                                          g.ss_reord_seen_W2_T.mean()) if len(g) else "n/a"
            rtx = "%.1f / %.1f" % (g.ss_retrans_W2_T.mean(), g.ss_retrans_W2_C.mean()) if len(g) else "n/a"
            r.update(reord_seen_T=g.ss_reord_seen_W2_T.mean() if len(g) else np.nan,
                     retrans_T=g.ss_retrans_W2_T.mean() if len(g) else np.nan,
                     retrans_C=g.ss_retrans_W2_C.mean() if len(g) else np.nan)
            rows.append(r)
            L.append("| s%d>s%d | %d | %s Mbit/s (n=%d) | %s | %s | %s |" % (
                p, q, nq, name, len(g), " | ".join(cells), reo, rtx))
    ex = hi[hi.replay_ok != 1]
    if len(ex):
        L += ["", "Excluded:"] + ["- trial %d: %s" % (int(r.trial), r.excluded) for _, r in ex.iterrows()]
    # pooled by direction at the pilot rate
    hi_ok = hi[hi.replay_ok == 1]
    L += ["", "Pooled at %g Mbit/s:" % a.mbps, ""]
    for lab, m in (("slow->fast", hi_ok.delay_gap_design_ms < 0),
                   ("fast->slow", hi_ok.delay_gap_design_ms > 0),
                   ("same delay", hi_ok.delay_gap_design_ms == 0)):
        g = hi_ok[m]
        L.append("- %s (n = %d): %s" % (lab, len(g), "; ".join(
            "%s %s" % (t, cell(mbps(g, t, w), a.mbps)) for t, w in TERMS)))
    pd.DataFrame(rows).to_csv(os.path.join(a.pilot, "regime_pilot.csv"), index=False,
                              float_format="%.6g")
    hi.to_csv(os.path.join(a.pilot, "regime_rows.csv"), index=False, float_format="%.10g")
    open(os.path.join(a.pilot, "regime_pilot.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
