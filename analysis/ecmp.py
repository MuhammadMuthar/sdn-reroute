#!/usr/bin/env python3
"""Chunk 3 analysis: the ECMP baseline campaign.

Reads <campaign>/runs.csv, flows.csv, links.csv (experiments/metrics.py) and
writes <campaign>/summary.md, <campaign>/summary.csv and
figures/ecmp_baseline.png. With a second campaign directory (a replay of
some of the same seeds) it also checks that the same seed gives the same
schedule and every flow the same spine.

Usage: .venv/bin/python analysis/ecmp.py results/ecmp/<campaign> [results/ecmp/<replay>]
"""

import itertools
import os
import sys

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
from scipy import stats  # noqa: E402

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)
from analysis.gate import mean_ci  # noqa: E402

INK, INK2 = "#1f1f1e", "#5f5e58"
SHARE_COLORS = {0: "#2a78d6", 1: "#e08a2c", 2: "#c2412d", 3: "#6b2a8a"}


def fmt_ci(x, f="%.2f"):
    m, h = mean_ci(x)
    return (f + " ± " + f) % (m, h) if not np.isnan(h) else f % m


def main():
    camp = sys.argv[1]
    replay = sys.argv[2] if len(sys.argv) > 2 else None
    runs = pd.read_csv(os.path.join(camp, "runs.csv"))
    flows = pd.read_csv(os.path.join(camp, "flows.csv"))
    # a run with a recorded error or a failed elephant is excluded, not averaged in
    bad = runs[runs.errors.fillna("").astype(str).str.len().gt(0) |
               (runs.elephants_ok < runs.n_elephants)]
    runs = runs[~runs.run_id.isin(bad.run_id)]
    flows = flows[flows.run_id.isin(runs.run_id)]
    el = flows[flows.kind == "elephant"].copy()
    mi = flows[flows.kind == "mouse"].copy()
    # elephants sharing each flow's uplink (data direction), per run
    load = el.groupby(["run_id", "spine"]).size().rename("elephants_on_spine")
    el = el.join(load, on=["run_id", "spine"])
    mi = mi.join(load, on=["run_id", "spine"])
    known = mi.spine.notna()
    mi.loc[known, "elephants_on_spine"] = mi.loc[known, "elephants_on_spine"].fillna(0)
    # every right-hand host receives one elephant, so a mouse also shares its
    # last hop with that elephant; how many elephants share *that* elephant's
    # uplink decides how hard it pushes on the mouse's last hop
    dst_el = el.set_index(["run_id", "dst"]).elephants_on_spine.rename("dst_elephant_sharing")
    mi = mi.join(dst_el, on=["run_id", "dst"])
    ok = mi[(mi.ok == 1) & known]

    L = ["# ECMP baseline: %s" % os.path.basename(camp), "",
         "Generated by `analysis/ecmp.py` from runs.csv / flows.csv / links.csv "
         "(experiments/metrics.py). Scenario ecmp_mixed: 4 elephants h1..h4 -> h5..h8 "
         "for 30 s, Poisson mice 10/s from each of h1..h4 to a random h5..h8, "
         "bounded-Pareto sizes (alpha 1.2, 2 KB to 1 MB). All links 10 Mbit/s, "
         "spines s1, s2 = 1 ms, s3 = 5 ms, s4 = 10 ms one way.", "",
         "## Per run", "",
         "| run | seed | elephant -> spine | elephants on busiest uplink | elephant goodput, "
         "mean / min, Mbit/s | sum | mice ok / all | FCT p50 / p99, ms | max link util "
         "| sender retrans | RTOs |", "|" + "---|" * 11]
    for _, r in runs.iterrows():
        L.append("| %s | %d | %s | %d | %.2f / %.2f | %.2f | %d / %d | %.1f / %.0f | %.3f "
                 "| %d | %d |" % (r.run_id, r.seed, r.elephant_spines.replace(";", " "),
                                  r.max_elephants_per_uplink, r.eleph_goodput_mean,
                                  r.eleph_goodput_min, r.eleph_goodput_sum, r.mice_ok, r.n_mice,
                                  r.fct_p50_ms, r.fct_p99_ms, r.max_link_util,
                                  r.snd_TcpRetransSegs, r.snd_TcpExtTCPTimeouts))
    keys = [("eleph_goodput_mean", "elephant goodput, mean of 4, Mbit/s"),
            ("eleph_goodput_min", "elephant goodput, worst of 4, Mbit/s"),
            ("eleph_goodput_sum", "elephant goodput, sum, Mbit/s"),
            ("max_elephants_per_uplink", "elephants on the busiest uplink"),
            ("uplinks_used_by_elephants", "uplinks carrying an elephant"),
            ("fct_p50_ms", "mice FCT p50, ms"), ("fct_p99_ms", "mice FCT p99, ms"),
            ("fct_p50_ms_fast", "mice FCT p50 on s1/s2, ms"),
            ("fct_p99_ms_fast", "mice FCT p99 on s1/s2, ms"),
            ("fct_p50_ms_slow", "mice FCT p50 on s3/s4, ms"),
            ("fct_p99_ms_slow", "mice FCT p99 on s3/s4, ms"),
            ("max_link_util", "max link utilisation (largest per-uplink mean)"),
            ("snd_TcpRetransSegs", "retransmitted segments, all senders"),
            ("snd_TcpExtTCPTimeouts", "RTOs, all senders"),
            ("mice_failed", "mice that failed (20 s timeout)"),
            ("mice_start_lag_p99_ms", "mice start lag p99, ms (generator fidelity)")]
    summ = []
    L += ["", "## Across runs (n = %d, mean ± 95 %% CI)" % len(runs), "",
          "| metric | value |", "|---|---|"]
    for k, lab in keys:
        m, h = mean_ci(runs[k])
        summ.append(dict(metric=k, label=lab, n=len(runs), mean=m, ci95=h))
        L.append("| %s | %s |" % (lab, fmt_ci(runs[k], "%.3g")))
    pd.DataFrame(summ).to_csv(os.path.join(camp, "summary.csv"), index=False,
                              float_format="%.6g")

    # FCT by size: the p99 above mixes in the largest mice (1 MB needs 0.8 s
    # at the full 10 Mbit/s), so also per size class, per-run percentiles
    L += ["", "## Mice FCT by size class (per-run percentiles, mean ± 95 % CI over runs, ms)",
          "", "| size | mice per run | p50 | p99 |", "|---|---|---|---|"]
    for lab, lo, hi in (("< 10 KB", 0, 10e3), ("10-100 KB", 10e3, 100e3),
                        (">= 100 KB", 100e3, 1e12)):
        g = ok[(ok["size"] >= lo) & (ok["size"] < hi)]
        per = g.groupby("run_id").fct_s.agg([lambda x: np.percentile(x, 50) * 1e3,
                                              lambda x: np.percentile(x, 99) * 1e3, "size"])
        per.columns = ["p50", "p99", "n"]
        L.append("| %s | %.0f | %s | %s |" % (lab, per.n.mean(), fmt_ci(per.p50, "%.1f"),
                                              fmt_ci(per.p99, "%.0f")))

    slow = ok.fct_s > 0.9
    L.append("")
    L.append("Handshake losses: %.1f %% of mice took more than 0.9 s to connect (a lost SYN "
             "or SYN-ACK waits for the 1 s initial RTO); they are %.0f %% of the mice with "
             "FCT above 0.9 s, so the p99 above is mostly the initial RTO, not transfer "
             "time." % (100 * (ok.connect_s > 0.9).mean(),
                        100 * (slow & (ok.connect_s > 0.9)).sum() / max(1, slow.sum())))

    # ---- spreading ----------------------------------------------------------
    L += ["", "## Do flows spread across the four paths?", ""]
    gcols = ["group_l1_bucket%d_bytes" % b for b in range(4)]
    gb = runs[gcols].sum()
    L.append("Bytes through each bucket of l1's select group, all runs "
             "(`ovs-ofctl dump-group-stats`, bucket b = spine b+1): " +
             ", ".join("s%d %.1f MB (%.1f %%)" % (b + 1, v / 1e6, 100 * v / gb.sum())
                       for b, v in enumerate(gb)) + ".")
    cnt = ok.spine.value_counts().reindex([1, 2, 3, 4], fill_value=0)
    chi = stats.chisquare(cnt)
    L.append("Mice per spine, all runs (spine captures): " +
             ", ".join("s%d %d" % (k, v) for k, v in cnt.items()) +
             "; chi-square against uniform p = %.3g." % chi.pvalue)
    ec = el.spine.value_counts().reindex([1, 2, 3, 4], fill_value=0)
    L.append("Elephants per spine, all runs: " +
             ", ".join("s%d %d" % (k, v) for k, v in ec.items()) + ".")
    dist = runs.max_elephants_per_uplink.value_counts().sort_index()
    ne = int(runs.n_elephants.iloc[0])
    allp = list(itertools.product(range(4), repeat=ne))   # uniform hashing, exact
    expect = {k: sum(max(np.bincount(p, minlength=4)) == k for p in allp) / len(allp)
              for k in range(1, ne + 1)}
    L.append("Busiest uplink carried k elephants in: " +
             ", ".join("k=%d %d runs" % (k, v) for k, v in dist.items()) +
             " (if %d flows were hashed uniformly onto 4 paths: %s)." % (
                 ne, ", ".join("k=%d %.1f %%" % (k, 100 * v) for k, v in expect.items())))
    L.append("Flows whose data used more than one spine: %d of %d (ECMP never moves a "
             "flow). Flows whose ACKs took a different spine than their data: %d."
             % (int((flows.n_spines > 1).sum()), int(flows.spine.notna().sum()),
                int(runs.flows_ack_spine_ne_data_spine.sum())))
    nos = int(mi.spine.isna().sum())
    if nos:
        L.append("Mice with no data seen on any uplink: %d." % nos)

    # ---- what drives FCT and elephant goodput ------------------------------
    L += ["", "## Mice FCT by how many elephants share the mouse's uplink "
          "(all runs pooled, ms)", "",
          "| elephants on the uplink | mice | p50 | p90 | p99 |", "|---|---|---|---|---|"]
    for k, g in ok.groupby("elephants_on_spine"):
        k = int(k)
        q = np.percentile(g.fct_s * 1e3, [50, 90, 99])
        L.append("| %d | %d | %.1f | %.1f | %.1f |" % (k, len(g), *q))
    L += ["", "## Mice FCT by both shared hops (all runs pooled, ms)", "",
          "Rows: elephants on the mouse's own uplink. Columns: elephants sharing the "
          "uplink of the elephant that ends at the mouse's destination (1 = that "
          "elephant runs near 10 Mbit/s into the destination's 10 Mbit/s last hop).", "",
          "| own uplink \\ dest. elephant's uplink | " + " | ".join(
              "%d: n, p50, p99" % k for k in sorted(ok.dst_elephant_sharing.dropna().unique()))
          + " |", "|---|" + "---|" * ok.dst_elephant_sharing.nunique()]
    for k, g in ok.groupby("elephants_on_spine"):
        k = int(k)
        cells = []
        for j in sorted(ok.dst_elephant_sharing.dropna().unique()):
            h = g[g.dst_elephant_sharing == j].fct_s * 1e3
            cells.append("%d, %.0f, %.0f" % (len(h), np.percentile(h, 50),
                                             np.percentile(h, 99)) if len(h) else "")
        L.append("| %d | %s |" % (k, " | ".join(cells)))
    if len(bad):
        L += ["", "Runs excluded (error recorded or an elephant failed): " +
              ", ".join("%s (%s)" % (r.run_id, r.errors or "elephant failed")
                        for _, r in bad.iterrows())]
    L += ["", "## Elephant goodput by how many elephants share its uplink "
          "(all runs pooled, Mbit/s)", "", "| elephants on the uplink | flows | mean | min | max |",
          "|---|---|---|---|---|"]
    for k, g in el.groupby("elephants_on_spine"):
        L.append("| %d | %d | %.2f | %.2f | %.2f |" % (k, len(g), g.goodput_mbps.mean(),
                                                     g.goodput_mbps.min(), g.goodput_mbps.max()))

    # ---- reproducibility ---------------------------------------------------
    if replay:
        rr = pd.read_csv(os.path.join(replay, "runs.csv"))
        rf = pd.read_csv(os.path.join(replay, "flows.csv"))
        L += ["", "## Same seed, same schedule, same paths (replay: %s)"
              % os.path.basename(replay), ""]
        m = runs.merge(rr, on="seed", suffixes=("", "_replay"))
        L.append("Seeds replayed: %s. Schedule sha256 identical: %d of %d. "
                 "Elephant placement identical: %d of %d." % (
                     ", ".join(str(s) for s in m.seed),
                     int((m.schedule_sha256 == m.schedule_sha256_replay).sum()), len(m),
                     int((m.elephant_spines == m.elephant_spines_replay).sum()), len(m)))
        a = flows[flows.kind != "other"][["seed", "kind", "id", "sport", "spine"]]
        b = rf[rf.kind != "other"][["seed", "kind", "id", "sport", "spine"]]
        j = a.merge(b, on=["seed", "kind", "id", "sport"], suffixes=("", "_replay"))
        same = int((j.spine == j.spine_replay).sum())
        L.append("Flows (elephants and mice) on the same spine in both: %d of %d." %
                 (same, len(j)))
        for k in ("eleph_goodput_mean", "fct_p50_ms", "fct_p99_ms"):
            L.append("%s, original vs replay: %s." % (k, ", ".join(
                "seed %d %.3g vs %.3g" % (r.seed, r[k], r[k + "_replay"])
                for _, r in m.iterrows())))
    open(os.path.join(camp, "summary.md"), "w").write("\n".join(L) + "\n")

    # ---- figure ------------------------------------------------------------
    plt.rcParams.update({"font.size": 9, "axes.edgecolor": INK2, "axes.labelcolor": INK,
                         "xtick.color": INK2, "ytick.color": INK2})
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(9, 3.6))
    for k, g in ok.groupby("elephants_on_spine"):
        x = np.sort(g.fct_s * 1e3)
        k = int(k)
        a1.plot(x, np.arange(1, len(x) + 1) / len(x), color=SHARE_COLORS.get(k, INK),
                lw=1.4, label="%d elephant%s on its uplink (n=%d)" % (k, "" if k == 1 else "s",
                                                                       len(x)))
    a1.set_xscale("log")
    a1.set_xlabel("mouse FCT, ms (log)")
    a1.set_ylabel("fraction of mice")
    a1.legend(frameon=False, fontsize=7.5, loc="lower right")
    rng = np.random.default_rng(0)
    for k, g in el.groupby("elephants_on_spine"):
        a2.scatter(k + rng.uniform(-0.12, 0.12, len(g)), g.goodput_mbps, s=14,
                   color=SHARE_COLORS.get(k, INK), alpha=0.8)
    a2.set_xticks(sorted(el.elephants_on_spine.unique()))
    a2.set_xlabel("elephants sharing the uplink")
    a2.set_ylabel("elephant goodput, Mbit/s")
    a2.set_ylim(0, 10)
    for ax in (a1, a2):
        ax.spines[["top", "right"]].set_visible(False)
        ax.grid(color="#e6e5df", lw=0.6)
    fig.suptitle("ECMP on the 4-path leaf-spine, %d seeded runs: hash collisions decide "
                 "both" % len(runs), fontsize=9, color=INK, x=0.01, ha="left")
    fig.tight_layout()
    os.makedirs(os.path.join(REPO, "figures"), exist_ok=True)
    fig.savefig(os.path.join(REPO, "figures", "ecmp_baseline.png"), dpi=150)
    print("\n".join(L))


if __name__ == "__main__":
    main()
