#!/usr/bin/env python3
"""Open vSwitch's own counters for the monitoring-artifact check (Chunk 5,
post hoc). Runs made with `runner.py ... --ovs-stats` have
ovs_counters_start.txt and ovs_counters_end.txt (ovs-appctl dpctl/show,
upcall/show, coverage/show). For every run: datapath lookups hit / missed /
lost over the run (missed = packets that went to ovs-vswitchd's slow path),
and the coverage counters that count slow-path work and revalidation.

The Chunk 4 finding (analysis/mice_reorder.py): with the Hedera-style
monitoring, about 470 of 1057 mice per run have packets reordered inside l1,
early in the flow, unless the flow's first packets pass more than 100 ms
after its SYN. The inference to check: the counting rule the controller
installs on each SYN makes Open vSwitch send packets of that flow through its
slow path while later ones take the fast path. Prediction: far more missed
lookups and revalidations per run with the monitoring than without.

  .venv/bin/python analysis/upcall_check.py results/compare/<campaign>
"""

import glob
import json
import os
import re
import sys

COVERAGE = ["upcall_ukey_replace", "rev_flow_table", "rev_reconfigure", "xlate_actions",
            "handler_duplicate_upcall", "upcall_flow_limit_hit", "dumped_new_flow",
            "revalidate_missed_dp_flow", "ukey_dp_change", "dpif_flow_put", "dpif_flow_del",
            "dpif_execute"]


def parse(path):
    txt = open(path).read()
    out = {}
    m = re.search(r"lookups: hit:(\d+) missed:(\d+) lost:(\d+)", txt)
    if m:
        out.update(hit=int(m.group(1)), missed=int(m.group(2)), lost=int(m.group(3)))
    for name, tot in re.findall(r"^(\w+)\s+.*?total: (\d+)", txt, re.M):
        out[name] = int(tot)
    return out


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    camp = sys.argv[1]
    rows = []
    for rd in sorted(glob.glob(os.path.join(camp, "runs", "*"))):
        a, b = (os.path.join(rd, "ovs_counters_%s.txt" % t) for t in ("start", "end"))
        if not (os.path.exists(a) and os.path.exists(b)):
            continue
        s, e = parse(a), parse(b)
        meta = json.load(open(os.path.join(rd, "meta.json")))
        sched = json.load(open(os.path.join(rd, "schedule.json")))
        r = dict(run_id=os.path.basename(rd), controller=meta["controller"], seed=sched["seed"],
                 flows=len(sched["elephants"]) + len(sched["mice"]))
        for k in ["hit", "missed", "lost"] + COVERAGE:
            r[k] = e.get(k, 0) - s.get(k, 0)
        rows.append(r)
    keys = ["flows", "hit", "missed", "lost"] + COVERAGE
    L = ["# Open vSwitch counters over each run, %s" % os.path.basename(os.path.abspath(camp)), "",
         "Generated by `analysis/upcall_check.py` (end minus start of ovs-appctl dpctl/show and "
         "coverage/show). Post hoc check of the monitoring artifact.", "",
         "| counter | " + " | ".join("%s (seed %d)" % (r["controller"], r["seed"]) for r in rows) + " |",
         "|---|" + "---|" * len(rows)]
    for k in keys:
        L.append("| %s | %s |" % (k, " | ".join(str(r[k]) for r in rows)))
    L += ["", "| per flow started | " + " | ".join(r["controller"] for r in rows) + " |",
          "|---|" + "---|" * len(rows)]
    for k in ("missed", "rev_flow_table", "upcall_ukey_replace", "dpif_execute"):
        L.append("| %s | %s |" % (k, " | ".join("%.2f" % (r[k] / r["flows"]) for r in rows)))
    open(os.path.join(camp, "upcall_check.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
