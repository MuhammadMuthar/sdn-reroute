#!/usr/bin/env python3
"""Chunk 6: five-way comparison on ecmp_mixed, seeds 1-10, one boot. ECMP,
Hedera-style and cooldown-only (and monitor-only) are Chunk 4's runs
(results/compare/compare-<date>); the cost-aware controllers, formula and ML,
ran the same seeds afterwards (results/compare/costaware-<date>). Uses
analysis/chunk4.py's metrics, per-controller table and paired contrasts.

  .venv/bin/python analysis/chunk6.py --chunk4 results/compare/compare-<date> \\
      --costaware results/compare/costaware-<date> --out results/compare/five-way-<date>
writes chunk6_summary.md, chunk6_contrasts.csv and chunk6_comparison.png in --out.
"""

import argparse
import os
import sys

import pandas as pd

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)
from analysis import chunk4  # noqa: E402

CTRLS = ["ecmp", "hedera", "cooldown", "costaware_formula", "costaware_ml"]
METRICS = ["eleph_goodput_mean", "eleph_goodput_min", "fct_p50_ms", "fct_p99_ms",
           "reroutes_per_min", "flaps_per_min", "snd_TcpRetransSegs"]


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--chunk4", required=True)
    ap.add_argument("--costaware", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    parts, excl = [], []
    for d in (a.chunk4, a.costaware):
        r, _, ex = chunk4.load_compare(d)
        parts.append(r)
        excl += ex
    runs = pd.concat(parts, ignore_index=True)
    runs = runs[runs.controller.isin(CTRLS)]
    ctrls = [c for c in CTRLS if c in set(runs.controller)]
    _, T1 = chunk4.per_controller_table(runs, ctrls)
    rows, L2 = [], ["| contrast | metric | n pairs | difference, mean [95 % CI] |", "|---|---|---|---|"]
    lab = {k: l for k, l, _ in chunk4.METRICS}
    for c in ("costaware_formula", "costaware_ml"):
        for ref in ("ecmp", "hedera", "cooldown"):
            for m in METRICS:
                d, mean, h = chunk4.paired(runs, c, ref, m)
                rows.append(dict(controller=c, reference=ref, metric=m, n=len(d), mean=mean, ci95=h))
                L2.append("| %s minus %s | %s | %d | %s [%s, %s] |" % (
                    chunk4.CTRL_LABEL.get(c, c), chunk4.CTRL_LABEL.get(ref, ref), lab.get(m, m),
                    len(d), chunk4.fmt(mean), chunk4.fmt(mean - h), chunk4.fmt(mean + h)))
    pd.DataFrame(rows).to_csv(os.path.join(a.out, "chunk6_contrasts.csv"), index=False,
                              float_format="%.6g")
    L = ["# Chunk 6: five-way comparison, ecmp_mixed seeds 1-10", "",
         "Generated by `analysis/chunk6.py` from %s and %s. Mean ± 95 %% CI over runs; contrasts "
         "paired by seed." % (os.path.relpath(a.chunk4, REPO), os.path.relpath(a.costaware, REPO)), ""]
    L += (["Excluded runs: " + "; ".join(excl), ""] if excl else ["No run excluded.", ""])
    L += T1 + ["", "## Cost-aware controllers, paired by seed", ""] + L2
    open(os.path.join(a.out, "chunk6_summary.md"), "w").write("\n".join(L) + "\n")
    chunk4.CTRL_COLOR.update(costaware_formula="#3a9a5b", costaware_ml="#8e5bb5")
    chunk4.fig_comparison(runs, ctrls, os.path.join(a.out, "chunk6_comparison.png"))
    print("\n".join(L))


if __name__ == "__main__":
    main()
